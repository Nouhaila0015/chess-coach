export const OPENING_LINES = LINES.map((l) => l.split(' '))

const PREFIXES = new Set<string>()
for (const line of OPENING_LINES) {
  for (let i = 1; i <= line.length; i++) PREFIXES.add(line.slice(0, i).join(' '))
}

// Vrai si la suite de coups (en notation algébrique anglaise) fait partie de la théorie.
export function isBook(sans: string[]): boolean {
  return PREFIXES.has(sans.join(' '))
}
